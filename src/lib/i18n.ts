export type TranslationKey = keyof typeof translations.ru

export function t(lang: Lang, key: TranslationKey): string {
  return translations[lang]?.[key] ?? translations.en[key] ?? key
}

/** Локализованный ярлык типа заказа (here/takeaway/delivery). */
export function orderTypeLabel(lang: Lang, type: 'here' | 'takeaway' | 'delivery'): string {
  return t(lang, type)
}

export function formatDate(date: string | Date, lang: Lang): string {
  return new Date(date).toLocaleString(localeOf(lang))
}

/** Только время «22:34» — для «стол открыт в …» и подобного */
export function formatTime(date: string | Date, lang: Lang): string {
  return new Date(date).toLocaleTimeString(localeOf(lang), {
    hour: '2-digit',
    minute: '2-digit',
  })
}

/** Сколько прошло часами и минутами: «00:12», «01:20» — карточка стола в зале */
export function formatElapsedHm(iso: string, nowTs: number): string {
  const mins = Math.max(0, Math.floor((nowTs - new Date(iso).getTime()) / 60000))
  const h = Math.floor(mins / 60)
  const m = mins % 60
  // Без padStart: его нет в WebView Chrome 52 на T2
  return `${h < 10 ? '0' : ''}${h}:${m < 10 ? '0' : ''}${m}`
}

/** Компактное «сколько прошло»: «5 мин», «1 ч 20 мин». nowTs — для реактивности. */
export function formatElapsed(iso: string, nowTs: number, lang: Lang): string {
  const mins = Math.max(0, Math.floor((nowTs - new Date(iso).getTime()) / 60000))
  if (mins < 1) return t(lang, 'justNow')
  if (mins < 60) return `${mins} ${t(lang, 'minShort')}`
  const h = Math.floor(mins / 60)
  const m = mins % 60
  return m === 0
    ? `${h} ${t(lang, 'hourShort')}`
    : `${h} ${t(lang, 'hourShort')} ${m} ${t(lang, 'minShort')}`
}
