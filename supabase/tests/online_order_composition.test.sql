-- Заявки шлём с разных телефонов: лимит частоты проверяется отдельно (T17).
CREATE FUNCTION pg_temp.submit(p_uuid UUID, p_items JSONB, p_phone TEXT DEFAULT NULL)
RETURNS JSON LANGUAGE sql AS $$
  SELECT submit_online_order(
    'e1000000-0000-4000-8000-000000000001', p_uuid, 'Гость',
    -- телефон уникален на заявку: лимит частоты проверяется отдельно (T17),
    -- а не мешает остальным пробам
    COALESCE(p_phone, '0501' || RIGHT(REPLACE(p_uuid::TEXT, '-', ''), 6)),
    p_items)
$$;

