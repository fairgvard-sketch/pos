--
-- Проверяется то, ради чего писались миграции:
--   * сквозной номер заявки — выдаётся, растёт и у каждой точки свой;
--   * история переходов — пишется триггером, знает автора и причину,
--     не засоряется правками без смены статуса;
--   * get_online_orders_web — разрезы дня точки не пересекаются,
--     право на действие приходит с сервера, поиск и пагинация работают,
--     чужая точка недоступна.
-- JWT-клеймы подменяются только внутри локальной транзакции теста.

