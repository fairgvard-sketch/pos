-- pgTAP: часы сотрудников по дням (143).
--
-- Проверяем то, из-за чего отчёт и заводился:
--  1) день смены = день ПРИХОДА в часовом поясе точки, а не в UTC и не в
--     поясе браузера (ночная смена не уезжает на соседний день);
--  2) период задан календарными датами включительно, обе границы внутри;
--  3) фильтры по сотруднику и по точке действительно сужают выборку;
--  4) удалённые записи (мягкое удаление) в часы не попадают;
--  5) гейт: без права manage отчёт не отдаётся, веб-владелец кабинета
--     проходит по членству;
--  6) правка табеля из кабинета: точка приходит параметром, автор
--     записывается в edited_by_user.
-- JWT-клеймы подменяются только внутри локальной транзакции теста.

BEGIN;
SELECT plan(13);

-- ── Фикстура: одна организация, две точки, два сотрудника ──
INSERT INTO orgs (id, name) VALUES
  ('c0000000-0000-4000-8000-000000000001', 'pgTAP org H1');

INSERT INTO locations (id, org_id, name) VALUES
  ('c1000000-0000-4000-8000-000000000001', 'c0000000-0000-4000-8000-000000000001', 'Loc H1'),
  ('c1000000-0000-4000-8000-000000000002', 'c0000000-0000-4000-8000-000000000001', 'Loc H2');

INSERT INTO staff (id, org_id, location_id, name, role, pin_hash, is_active) VALUES
  ('c2000000-0000-4000-8000-000000000001', 'c0000000-0000-4000-8000-000000000001',
   'c1000000-0000-4000-8000-000000000001', 'Аня', 'barista', 'x', TRUE),
  ('c2000000-0000-4000-8000-000000000002', 'c0000000-0000-4000-8000-000000000001',
   'c1000000-0000-4000-8000-000000000002', 'Дана', 'barista', 'x', TRUE);

INSERT INTO auth.users (id) VALUES
  ('c3000000-0000-4000-8000-000000000001');  -- веб-владелец кабинета

INSERT INTO organization_members (org_id, auth_user_id, role, is_active) VALUES
  ('c0000000-0000-4000-8000-000000000001', 'c3000000-0000-4000-8000-000000000001', 'owner', TRUE);

-- Смены Ани:
--   * 01.08 07:00–15:00 по Иерусалиму (04:00–12:00 UTC) — обычный день;
--   * 03.08 22:30–06:30 следующих суток — НОЧНАЯ: принадлежит 03.08;
--   * 05.08 — мягко удалённая, в часы попасть не должна.
-- Смена Даны на второй точке 02.08 — для проверки фильтра по точке.
INSERT INTO time_entries (id, org_id, location_id, staff_id, clock_in, clock_out, deleted_at) VALUES
  ('c4000000-0000-4000-8000-000000000001', 'c0000000-0000-4000-8000-000000000001',
   'c1000000-0000-4000-8000-000000000001', 'c2000000-0000-4000-8000-000000000001',
   '2026-08-01 04:00:00+00', '2026-08-01 12:00:00+00', NULL),
  ('c4000000-0000-4000-8000-000000000002', 'c0000000-0000-4000-8000-000000000001',
   'c1000000-0000-4000-8000-000000000001', 'c2000000-0000-4000-8000-000000000001',
   '2026-08-03 19:30:00+00', '2026-08-04 03:30:00+00', NULL),
  ('c4000000-0000-4000-8000-000000000003', 'c0000000-0000-4000-8000-000000000001',
   'c1000000-0000-4000-8000-000000000001', 'c2000000-0000-4000-8000-000000000001',
   '2026-08-05 04:00:00+00', '2026-08-05 12:00:00+00', NOW()),
  ('c4000000-0000-4000-8000-000000000004', 'c0000000-0000-4000-8000-000000000001',
   'c1000000-0000-4000-8000-000000000002', 'c2000000-0000-4000-8000-000000000002',
   '2026-08-02 05:00:00+00', '2026-08-02 11:00:00+00', NULL);

SET LOCAL ROLE authenticated;

-- ============================================================
-- Веб-владелец кабинета: членство вместо PIN-сессии
-- ============================================================
SELECT set_config(
  'request.jwt.claims',
  '{"sub":"c3000000-0000-4000-8000-000000000001","role":"authenticated","app_metadata":{"org_id":"c0000000-0000-4000-8000-000000000001"}}',
  true
);

CREATE TEMP TABLE aug AS
SELECT staff_hours_report(
  DATE '2026-08-01', DATE '2026-08-31', 'Asia/Jerusalem',
  ARRAY['c2000000-0000-4000-8000-000000000001']::UUID[], NULL, NULL
) AS r;

-- 1. Мягко удалённая смена в часы не попадает: две смены, а не три
SELECT is(
  (SELECT (r #>> '{staff,0,shifts}')::INT FROM aug),
  2,
  'удалённая запись табеля в часы не входит'
);

-- 2. Часы считаются по факту: 8 + 8
SELECT is(
  (SELECT (r #>> '{staff,0,seconds}')::INT FROM aug),
  16 * 3600,
  'сумма часов за период — по закрытым сменам'
);

-- 3. Обычная смена лежит в дне прихода
SELECT is(
  (SELECT r #>> '{staff,0,entries,0,day}' FROM aug),
  '2026-08-01',
  'дневная смена принадлежит своей дате'
);

-- 4. Ночная смена принадлежит дню НАЧАЛА, а не дню ухода.
-- 03.08 22:30 по Иерусалиму = 19:30 UTC: по UTC это тоже 3-е, но уход уже
-- 4-го — именно на этом ломался клиентский подсчёт.
SELECT is(
  (SELECT r #>> '{staff,0,entries,1,day}' FROM aug),
  '2026-08-03',
  'ночная смена принадлежит дню прихода'
);

-- 5. День недели считается в поясе точки: 01.08.2026 — суббота (6)
SELECT is(
  (SELECT (r #>> '{staff,0,entries,0,dow}')::INT FROM aug),
  6,
  'день недели — по календарю точки, воскресенье = 0'
);

-- 6. Граница периода включительна с обеих сторон
SELECT is(
  (SELECT (staff_hours_report(DATE '2026-08-01', DATE '2026-08-01', 'Asia/Jerusalem',
           ARRAY['c2000000-0000-4000-8000-000000000001']::UUID[], NULL, NULL)
           #>> '{staff,0,shifts}')::INT),
  1,
  'однодневный период отдаёт смену этого дня'
);

-- 7. Фильтр по сотруднику: чужие смены не подмешиваются
SELECT is(
  (SELECT jsonb_array_length(r -> 'staff') FROM aug),
  1,
  'спросили одного сотрудника — отдан один'
);

-- 8. Сотрудник без смен, спрошенный поимённо, возвращается с нулём
SELECT is(
  (SELECT (staff_hours_report(DATE '2026-09-01', DATE '2026-09-30', 'Asia/Jerusalem',
           ARRAY['c2000000-0000-4000-8000-000000000001']::UUID[], NULL, NULL)
           #>> '{staff,0,seconds}')::INT),
  0,
  'месяц без смен — не «сотрудник не найден», а ноль часов'
);

-- 9. Фильтр по точке
SELECT is(
  (SELECT (staff_hours_report(DATE '2026-08-01', DATE '2026-08-31', 'Asia/Jerusalem',
           NULL, ARRAY['c1000000-0000-4000-8000-000000000002']::UUID[], NULL)
           #>> '{staff,0,name}')),
  'Дана',
  'фильтр по точке оставляет только её сотрудников'
);

-- 10. Без фильтров видны обе точки
SELECT is(
  (SELECT (staff_hours_report(DATE '2026-08-01', DATE '2026-08-31', 'Asia/Jerusalem',
           NULL, NULL, NULL) #>> '{totals,staff}')::INT),
  2,
  'без фильтра в отчёте вся организация'
);

-- 11. Правка из кабинета: точка приходит параметром (в JWT её нет),
--     автор записывается в edited_by_user.
-- Время берётся от NOW(): сервер не принимает приход в будущем, а тест
-- обязан проходить в любой день, а не только после августа 2026.
SELECT lives_ok(
  $$ SELECT save_time_entry(NULL, 'c2000000-0000-4000-8000-000000000001',
       NOW() - INTERVAL '2 days', NOW() - INTERVAL '2 days' + INTERVAL '8 hours',
       NULL, 'забыл отметиться', NULL, 'c1000000-0000-4000-8000-000000000001') $$,
  'веб-владелец добавляет смену задним числом'
);

SELECT is(
  (SELECT edited_by_user FROM time_entries
   WHERE staff_id = 'c2000000-0000-4000-8000-000000000001'
     AND note = 'забыл отметиться'),
  'c3000000-0000-4000-8000-000000000001'::UUID,
  'автор правки из кабинета сохранён'
);

-- ============================================================
-- Касса без manage-сессии: зарплатные часы не отдаются
-- ============================================================
SELECT set_config(
  'request.jwt.claims',
  '{"role":"authenticated","app_metadata":{"org_id":"c0000000-0000-4000-8000-000000000001","location_id":"c1000000-0000-4000-8000-000000000001"}}',
  true
);

SELECT throws_ok(
  $$ SELECT staff_hours_report(DATE '2026-08-01', DATE '2026-08-31',
       'Asia/Jerusalem', NULL, NULL, NULL) $$,
  NULL,
  'staff session required',
  'без manage-сессии отчёт по часам закрыт'
);

