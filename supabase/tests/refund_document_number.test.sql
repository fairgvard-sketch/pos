  'request.jwt.claims',
  '{"sub":"49700000-0000-4000-8000-000000000001","role":"authenticated","app_metadata":{"org_id":"49000000-0000-4000-8000-000000000001","location_id":"49100000-0000-4000-8000-000000000001"}}',
