   '49200000-0000-4000-8000-000000000001', 'open', 0),
  ('49400000-0000-4000-8000-000000000002',
   '49000000-0000-4000-8000-000000000001',
   '49100000-0000-4000-8000-000000000002',
   '49200000-0000-4000-8000-000000000002', 'open', 0);

-- Два оплаченных заказа в первой точке и один во второй
INSERT INTO orders (
