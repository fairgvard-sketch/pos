  SELECT issue_refund(
    '49800000-0000-4000-8000-000000000003'::uuid,
    '49500000-0000-4000-8000-000000000003'::uuid,
    '49200000-0000-4000-8000-000000000002'::uuid,
    700, 'cash', 'возврат второй точки', NULL,
    '49300000-0000-4000-8000-000000000002'::uuid
  )
