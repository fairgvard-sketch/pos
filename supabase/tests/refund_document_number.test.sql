  (SELECT refund_number FROM refunds WHERE id = '49800000-0000-4000-8000-000000000002'),
  2,
  'следующий зикуй точки — 2: нумерация без пропусков'
);

-- ── Повтор не тратит номер ───────────────────────────────────
-- Офлайн-очередь повторяет операцию после таймаута. Пропуск в
