    '49800000-0000-4000-8000-000000000002'::uuid,
    '49500000-0000-4000-8000-000000000002'::uuid,
    '49200000-0000-4000-8000-000000000001'::uuid,
    500, 'cash', 'второй возврат', NULL,
    '49300000-0000-4000-8000-000000000001'::uuid
