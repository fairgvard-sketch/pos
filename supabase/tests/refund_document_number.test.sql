-- pgTAP: номер документа возврата (миграция 149).
--
-- Регресс, который этот набор ловит: 029 завела для תעודת זיכוי свою
-- сквозную нумерацию внутри `issue_refund`, 044 переписала функцию под
-- staff-сессии и потеряла её, 046 перенесла потерю дальше. Возвраты
-- создавались с location_id = NULL и refund_number = NULL, поэтому не
-- попадали в выгрузку Единого формата (она отбирает по обоим полям) и
-- печатались с прочерком вместо номера.
--
-- Прежний набор uf_export.test.sql этого не видел: он вставлял возврат
-- в таблицу НАПРЯМУЮ, руками подставляя и точку, и номер, — то есть
-- проверял выборку на данных, которых production не создавал.
--
-- Поэтому здесь возврат проводится настоящим RPC, тем самым, что
-- вызывает касса. Проверяется не механизм (триггер), а обещание:
-- проведённый возврат — это документ с точкой и непрерывным номером.

BEGIN;
SELECT plan(12);

-- ── Триггер на месте ─────────────────────────────────────────
SELECT has_trigger(
  'public', 'refunds', 'trg_refunds_document_number',
  'refunds carries the document-number trigger'
);
SELECT ok(
  NOT has_function_privilege('anon', 'refunds_assign_document_number()', 'EXECUTE'),
  'anon cannot execute the numbering function'
);

-- ── Фикстура: две точки одной организации ────────────────────
-- Вторая точка нужна, чтобы поймать вторую половину требования:
-- нумерация непрерывна ВНУТРИ точки и не общая на организацию.
INSERT INTO orgs (id, name)
