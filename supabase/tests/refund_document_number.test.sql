  ('49300000-0000-4000-8000-000000000002',
   '49200000-0000-4000-8000-000000000002',
   '49000000-0000-4000-8000-000000000001',
   '49100000-0000-4000-8000-000000000002');

INSERT INTO shifts (id, org_id, location_id, opened_by, status, opening_float) VALUES
  ('49400000-0000-4000-8000-000000000001',
   '49000000-0000-4000-8000-000000000001',
