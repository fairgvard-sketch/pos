SELECT is(
  (SELECT refund_number FROM refunds WHERE id = '49800000-0000-4000-8000-000000000003'),
  1,
  'у второй точки своя череда номеров, а не общая с первой'
);

-- ── Возврат виден выгрузке Единого формата ───────────────────
-- Ради этого всё и делается: документ 330 обязан попасть в набор.
SELECT is(
  (SELECT COUNT(*)::int
   FROM jsonb_array_elements(
     uf_export_documents_for(
       '49100000-0000-4000-8000-000000000001'::uuid,
       (NOW() AT TIME ZONE 'Asia/Jerusalem')::date,
       (NOW() AT TIME ZONE 'Asia/Jerusalem')::date,
       NULL, NULL, 200
     ) -> 'documents'
   ) AS d
   WHERE d ->> 'kind' = 'refund'),
  2,
  'оба зикуя точки попали в выгрузку — до 149 их там не было ни одного'
);

SELECT * FROM finish();
