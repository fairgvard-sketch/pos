-- pgTAP: окончательное удаление терминала из кабинета (135).
--
-- Здесь проверяется не «функция отработала», а четыре обещания, каждое
-- из которых стоит дороже кода:
--   1. удаление закрывает вход — иначе касса зарегистрируется заново
--      и вернётся в список (register_device идемпотентна);
--   2. учётка ЧЕЛОВЕКА не удаляется никогда, даже если он оказался
--      привязан к строке терминала;
--   3. терминал с неотправленной очередью удалить нельзя — там деньги;
--   4. заказы, смены и события остаются: финансовые записи не исчезают
--      вместе с железом.

BEGIN;
SELECT plan(17);

INSERT INTO orgs (id, name) VALUES
  ('d0000000-0000-4000-8000-000000000001', 'pgTAP delete A'),
  ('d0000000-0000-4000-8000-000000000002', 'pgTAP delete B');
INSERT INTO locations (id, org_id, name, timezone) VALUES
  ('d1000000-0000-4000-8000-000000000001',
   'd0000000-0000-4000-8000-000000000001', 'Главная', 'Asia/Jerusalem'),
  ('d1000000-0000-4000-8000-000000000002',
   'd0000000-0000-4000-8000-000000000002', 'Чужая', 'Asia/Jerusalem');

-- Учётки: терминальная, общая на два терминала, и человек-владелец
INSERT INTO auth.users (id) VALUES
  ('d4000000-0000-4000-8000-0000000000a1'),   -- только терминал №1
  ('d4000000-0000-4000-8000-0000000000a2'),   -- общая на №2 и №3
  ('d4000000-0000-4000-8000-0000000000ff');   -- владелец-человек

INSERT INTO organization_members (id, org_id, auth_user_id, role, is_active) VALUES
  ('d5000000-0000-4000-8000-000000000001',
   'd0000000-0000-4000-8000-000000000001', 'd4000000-0000-4000-8000-0000000000ff',
   'owner', TRUE);

INSERT INTO devices (id, org_id, location_id, name, auth_user_id, last_seen_at, archived_at, outbox_pending) VALUES
  -- №1: архивный, своя учётка, очередь пуста — удаляется полностью
  ('d2000000-0000-4000-8000-000000000001', 'd0000000-0000-4000-8000-000000000001',
   'd1000000-0000-4000-8000-000000000001', 'Списанная', 'd4000000-0000-4000-8000-0000000000a1',
   NOW() - INTERVAL '40 days', NOW(), 0),
  -- №2: архивный, но с неотправленной очередью
  ('d2000000-0000-4000-8000-000000000002', 'd0000000-0000-4000-8000-000000000001',
   'd1000000-0000-4000-8000-000000000001', 'С очередью', 'd4000000-0000-4000-8000-0000000000a2',
   NOW() - INTERVAL '2 days', NOW(), 3),
  -- №3: делит учётку с №2
  ('d2000000-0000-4000-8000-000000000003', 'd0000000-0000-4000-8000-000000000001',
   'd1000000-0000-4000-8000-000000000001', 'Соседняя', 'd4000000-0000-4000-8000-0000000000a2',
   NOW(), NULL, 0),
  -- №4: НЕ в архиве
  ('d2000000-0000-4000-8000-000000000004', 'd0000000-0000-4000-8000-000000000001',
   'd1000000-0000-4000-8000-000000000001', 'Рабочая', NULL, NOW(), NULL, 0),
  -- №5: архивный, но привязан к учётке ЧЕЛОВЕКА
  ('d2000000-0000-4000-8000-000000000005', 'd0000000-0000-4000-8000-000000000001',
   'd1000000-0000-4000-8000-000000000001', 'Ноутбук владельца', 'd4000000-0000-4000-8000-0000000000ff',
   NOW(), NOW(), 0),
  -- №6: чужая организация
  ('d2000000-0000-4000-8000-0000000000ff', 'd0000000-0000-4000-8000-000000000002',
   'd1000000-0000-4000-8000-000000000002', 'Чужая касса', NULL, NOW(), NOW(), 0);

-- Событие журнала на удаляемом терминале: оно обязано пережить удаление
INSERT INTO activity_events (id, org_id, location_id, device_id, type, created_at)
VALUES ('d6000000-0000-4000-8000-000000000001',
        'd0000000-0000-4000-8000-000000000001', 'd1000000-0000-4000-8000-000000000001',
        'd2000000-0000-4000-8000-000000000001', 'shift_closed', NOW());

SET LOCAL ROLE authenticated;
SELECT set_config(
  'request.jwt.claims',
  '{"sub":"d4000000-0000-4000-8000-0000000000ff","role":"authenticated","app_metadata":{"org_id":"d0000000-0000-4000-8000-000000000001"}}',
  true
);

-- ── Отказы ──────────────────────────────────────────────────
SELECT throws_ok(
  $$SELECT delete_device_web('d2000000-0000-4000-8000-000000000004')$$,
  'not_archived',
  'работающую кассу удалить нельзя — сначала архив');
SELECT throws_ok(
  $$SELECT delete_device_web('d2000000-0000-4000-8000-000000000002')$$,
  'outbox_pending',
  'касса с неотправленной очередью не удаляется — там деньги');
SELECT throws_ok(
  $$SELECT delete_device_web('d2000000-0000-4000-8000-0000000000ff')$$,
  'not_found',
  'чужой терминал удалить нельзя');

RESET ROLE;
SELECT is(
  (SELECT count(*)::INTEGER FROM devices WHERE id = 'd2000000-0000-4000-8000-0000000000ff'),
  1, 'чужой терминал на месте');
SELECT is(
  (SELECT count(*)::INTEGER FROM devices WHERE id = 'd2000000-0000-4000-8000-000000000002'),
  1, 'касса с очередью на месте');
SET LOCAL ROLE authenticated;

-- ── Удаление терминальной учётки ────────────────────────────
SELECT is(
  (SELECT (delete_device_web('d2000000-0000-4000-8000-000000000001')::jsonb ->> 'access_revoked')),
  'true',
  'вход терминала закрыт — иначе он вернётся сам');

RESET ROLE;
SELECT is(
  (SELECT count(*)::INTEGER FROM devices WHERE id = 'd2000000-0000-4000-8000-000000000001'),
  0, 'строка парка удалена');
SELECT is(
  (SELECT count(*)::INTEGER FROM auth.users WHERE id = 'd4000000-0000-4000-8000-0000000000a1'),
  0, 'учётка терминала удалена');

-- Финансовые следы остаются
SELECT is(
  (SELECT count(*)::INTEGER FROM activity_events WHERE id = 'd6000000-0000-4000-8000-000000000001'),
  1, 'событие журнала не удалено вместе с терминалом');
SELECT is(
  (SELECT device_id FROM activity_events WHERE id = 'd6000000-0000-4000-8000-000000000001'),
  NULL, 'ссылка на терминал обнулена, событие осталось с точкой');
SET LOCAL ROLE authenticated;

-- ── Учётка человека не удаляется ────────────────────────────
-- Результат одного вызова: удаление необратимо, повторно вызвать нельзя
CREATE TEMP TABLE member_result AS
  SELECT delete_device_web('d2000000-0000-4000-8000-000000000005')::jsonb AS j;
SELECT is(
  (SELECT j ->> 'access_revoked' FROM member_result), 'false',
  'аккаунт человека вход не теряет');
SELECT is(
  (SELECT j ->> 'reason' FROM member_result), 'account_is_member',
  'и причина названа прямо');

RESET ROLE;
SELECT is(
  (SELECT count(*)::INTEGER FROM auth.users WHERE id = 'd4000000-0000-4000-8000-0000000000ff'),
  1, 'учётка владельца цела');
SELECT is(
  (SELECT count(*)::INTEGER FROM organization_members
   WHERE auth_user_id = 'd4000000-0000-4000-8000-0000000000ff'),
  1, 'членство владельца цело');
SET LOCAL ROLE authenticated;

-- ── Общая учётка двух касс ──────────────────────────────────
-- Освобождаем очередь, чтобы дойти до проверки общей учётки
RESET ROLE;
UPDATE devices SET outbox_pending = 0
WHERE id = 'd2000000-0000-4000-8000-000000000002';
SET LOCAL ROLE authenticated;

CREATE TEMP TABLE shared_result AS
  SELECT delete_device_web('d2000000-0000-4000-8000-000000000002')::jsonb AS j;
SELECT is(
  (SELECT j ->> 'reason' FROM shared_result), 'account_shared',
  'учётку, на которой висит работающая касса, не трогаем');
SELECT is(
  (SELECT j ->> 'deleted' FROM shared_result), 'true',
  'сама строка парка при этом удалена');

RESET ROLE;
SELECT is(
  (SELECT count(*)::INTEGER FROM auth.users WHERE id = 'd4000000-0000-4000-8000-0000000000a2'),
  1, 'общая учётка цела — соседняя касса продолжает работать');

SELECT * FROM finish();
ROLLBACK;
