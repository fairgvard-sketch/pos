-- pgTAP: план зала из веб-кабинета (123).
--
-- Проверяется то, ради чего миграция появилась: организация с одним лишь
-- Reserve заводит зоны и столы БЕЗ кассы и без PIN, а стол с обещанным
-- гостю визитом не исчезает с плана одним тапом.
-- JWT-клеймы подменяются только внутри локальной транзакции теста.

BEGIN;
SELECT plan(16);

-- ── Фикстура ─────────────────────────────────────────────────
-- A — standalone Reserve (кассы нет вовсе), B — организация без
-- Reserve и без POS: у неё план зала должен быть закрыт.
INSERT INTO orgs (id, name) VALUES
  ('c0000000-0000-4000-8000-000000000001', 'pgTAP floor A'),
  ('c0000000-0000-4000-8000-000000000002', 'pgTAP floor B');

INSERT INTO locations (id, org_id, name) VALUES
  ('c1000000-0000-4000-8000-000000000001', 'c0000000-0000-4000-8000-000000000001', 'Floor loc A'),
  ('c1000000-0000-4000-8000-000000000002', 'c0000000-0000-4000-8000-000000000002', 'Floor loc B');

INSERT INTO organization_products (org_id, product) VALUES
  ('c0000000-0000-4000-8000-000000000001', 'reservations'),
  ('c0000000-0000-4000-8000-000000000002', 'menu');

INSERT INTO auth.users (id) VALUES
  ('c4000000-0000-4000-8000-000000000001'),
  ('c4000000-0000-4000-8000-000000000002');

INSERT INTO organization_members (id, org_id, auth_user_id, role, is_active) VALUES
  ('c5000000-0000-4000-8000-000000000001',
   'c0000000-0000-4000-8000-000000000001', 'c4000000-0000-4000-8000-000000000001', 'owner', TRUE),
  ('c5000000-0000-4000-8000-000000000002',
   'c0000000-0000-4000-8000-000000000002', 'c4000000-0000-4000-8000-000000000002', 'owner', TRUE);

SET LOCAL ROLE authenticated;
SELECT set_config(
  'request.jwt.claims',
  '{"sub":"c4000000-0000-4000-8000-000000000001","role":"authenticated","app_metadata":{"org_id":"c0000000-0000-4000-8000-000000000001"}}',
  true
);

-- ── Зона с набором столов ────────────────────────────────────
SELECT is(
  (SELECT (create_table_zone_web(
    'c1000000-0000-4000-8000-000000000001',
    'c2000000-0000-4000-8000-000000000001',
    'Терраса', 0, 3, 'T', 0, 4
  )).name),
  'Терраса',
  'владелец standalone Reserve заводит зону без кассы и PIN'
);
SELECT is(
  (SELECT COUNT(*)::INTEGER FROM tables
   WHERE zone_id = 'c2000000-0000-4000-8000-000000000001' AND is_active),
  3,
  'вместе с зоной созданы её столы'
);
SELECT is(
  (SELECT COUNT(DISTINCT seats)::INTEGER || ':' || MIN(seats)::TEXT FROM tables
   WHERE zone_id = 'c2000000-0000-4000-8000-000000000001'),
  '1:4',
  'вместимость столов взята из параметра, а не из умолчания 2'
);

-- Идемпотентность: повтор после таймаута не удваивает зал
SELECT lives_ok(
  $$SELECT create_table_zone_web(
    'c1000000-0000-4000-8000-000000000001',
    'c2000000-0000-4000-8000-000000000001',
    'Терраса', 0, 3, 'T', 0, 4
  )$$,
  'повтор с тем же UUID зоны не ошибка'
);
SELECT is(
  (SELECT COUNT(*)::INTEGER FROM tables
   WHERE zone_id = 'c2000000-0000-4000-8000-000000000001' AND is_active),
  3,
  'повтор не создал столы второй раз'
);

SELECT throws_ok(
  $$SELECT create_table_zone_web(
    'c1000000-0000-4000-8000-000000000001',
    'c2000000-0000-4000-8000-000000000009',
    'терраса', 1, 0, '', 0, 2
  )$$,
  'zone_exists',
  'зона с тем же именем (без учёта регистра) отклоняется'
);

-- ── Переименование тянет снимок в столы ──────────────────────
SELECT lives_ok(
  $$SELECT rename_table_zone_web(
    'c1000000-0000-4000-8000-000000000001',
    'c2000000-0000-4000-8000-000000000001',
    'Веранда'
  )$$,
  'зона переименована из кабинета'
);
SELECT is(
  (SELECT COUNT(*)::INTEGER FROM tables
   WHERE zone_id = 'c2000000-0000-4000-8000-000000000001' AND zone = 'Веранда'),
  3,
  'текстовый снимок зоны в столах обновлён'
);

-- ── Стол поимённо ────────────────────────────────────────────
SELECT is(
  (SELECT (save_table_web(
    'c1000000-0000-4000-8000-000000000001',
    'c3000000-0000-4000-8000-000000000001',
    'VIP', 'c2000000-0000-4000-8000-000000000001', 8, TRUE, 10
  )).seats),
  8,
  'стол заведён поимённо с вместимостью'
);
SELECT is(
  (SELECT (save_table_web(
    'c1000000-0000-4000-8000-000000000001',
    'c3000000-0000-4000-8000-000000000001',
    'VIP', 'c2000000-0000-4000-8000-000000000001', 6, TRUE, 10
  )).seats),
  6,
  'повтор по тому же id правит стол, а не создаёт второй'
);
SELECT is(
  (SELECT COUNT(*)::INTEGER FROM tables
   WHERE location_id = 'c1000000-0000-4000-8000-000000000001' AND is_active),
  4,
  'в зале ровно четыре стола'
);
SELECT throws_ok(
  $$SELECT save_table_web(
    'c1000000-0000-4000-8000-000000000001',
    'c3000000-0000-4000-8000-000000000002',
    'vip', 'c2000000-0000-4000-8000-000000000001', 2, FALSE, 11
  )$$,
  'table_exists',
  'дубль названия стола отклоняется при создании'
);
SELECT throws_ok(
  $$SELECT save_table_web(
    'c1000000-0000-4000-8000-000000000001',
    'c3000000-0000-4000-8000-000000000003',
    'Балкон', 'c2000000-0000-4000-8000-000000000099', 2, FALSE, 12
  )$$,
  'invalid_zone',
  'зона чужой точки / несуществующая зона отклоняется'
);

-- ── Стол с живой бронью впереди не убирается ─────────────────
-- Бронь заводит сервер (Edge Function под service_role): роли
-- authenticated INSERT в reservations не выдан (070/071).
RESET ROLE;
INSERT INTO reservations (id, org_id, location_id, client_uuid, customer_name,
                          customer_phone, party_size, reserved_at, status, table_id)
VALUES ('c6000000-0000-4000-8000-000000000001',
        'c0000000-0000-4000-8000-000000000001',
        'c1000000-0000-4000-8000-000000000001',
        'c7000000-0000-4000-8000-000000000001', 'Гость', '0501112233', 4,
        NOW() + INTERVAL '3 hours', 'confirmed',
        'c3000000-0000-4000-8000-000000000001');
SET LOCAL ROLE authenticated;

SELECT throws_ok(
  $$SELECT delete_table_web(
    'c1000000-0000-4000-8000-000000000001',
    'c3000000-0000-4000-8000-000000000001'
  )$$,
  'table_booked',
  'стол с обещанным визитом впереди с плана не снимается'
);

-- Свободный стол убирается мягко
SELECT lives_ok(
  $$SELECT delete_table_web(
    'c1000000-0000-4000-8000-000000000001',
    (SELECT id FROM tables
     WHERE zone_id = 'c2000000-0000-4000-8000-000000000001'
       AND label = 'T1' AND is_active)
  )$$,
  'свободный стол убирается с плана'
);

-- ── Организация без Reserve и без POS ────────────────────────
SELECT set_config(
  'request.jwt.claims',
  '{"sub":"c4000000-0000-4000-8000-000000000002","role":"authenticated","app_metadata":{"org_id":"c0000000-0000-4000-8000-000000000002"}}',
  true
);
SELECT throws_ok(
  $$SELECT create_table_zone_web(
    'c1000000-0000-4000-8000-000000000002',
    'c2000000-0000-4000-8000-000000000002',
    'Зал', 0, 2, 'A', 0, 2
  )$$,
  'module_disabled',
  'без Reserve и без POS план зала закрыт'
);

SELECT * FROM finish();
ROLLBACK;
