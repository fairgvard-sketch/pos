-- pgTAP: план зала и свойства стола из кабинета (138).
--
-- Раскладка существовала с 017, но правила её только касса: владелец
-- Reserve без POS не мог расставить столы вообще. Плюс два свойства,
-- которых не было нигде: «двойку за шестёрку не сажаем» и «этот стол
-- автоподбору не отдаём».
--
-- Проверяется главное: план сохраняется целиком и под правами кабинета,
-- а новые свойства РЕАЛЬНО влияют на подбор — иначе это переключатели,
-- которые ничего не переключают.

