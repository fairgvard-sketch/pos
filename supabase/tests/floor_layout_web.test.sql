CREATE FUNCTION pg_temp.as_owner() RETURNS VOID LANGUAGE sql AS $$
  SELECT set_config('request.jwt.claims', json_build_object(
    'sub', 'a8900000-0000-4000-8000-000000000001',
    'app_metadata', json_build_object('org_id', 'a8000000-0000-4000-8000-000000000001')
  )::text, TRUE)
$$;

CREATE FUNCTION pg_temp.as_stranger() RETURNS VOID LANGUAGE sql AS $$
  SELECT set_config('request.jwt.claims', json_build_object(
    'sub', 'a8900000-0000-4000-8000-000000000009',
    'app_metadata', json_build_object('org_id', 'a8000000-0000-4000-8000-000000000009')
  )::text, TRUE)
$$;

CREATE FUNCTION pg_temp.pick(p_party INTEGER) RETURNS UUID[] LANGUAGE sql STABLE AS $$
  SELECT _pick_tables('a8100000-0000-4000-8000-000000000001', p_party,
                      date_trunc('hour', NOW() + INTERVAL '3 hours'), 90, 0, FALSE, NULL, NULL)
$$;

SELECT pg_temp.as_owner();

-- ── 1. Раскладка сохраняется целиком ─────────────────────────
SELECT is(
  save_floor_layout_web('a8100000-0000-4000-8000-000000000001', '[
    {"id": "a8200000-0000-4000-8000-000000000001", "x": 10, "y": 20, "w": 12, "h": 12, "shape": "circle"},
    {"id": "a8200000-0000-4000-8000-000000000002", "x": 60, "y": 40}
  ]'::jsonb),
  2,
  'план зала сохраняется одним вызовом'
);

SELECT is(
  (SELECT pos_x::INTEGER || '/' || pos_y::INTEGER || '/' || shape FROM tables
   WHERE id = 'a8200000-0000-4000-8000-000000000001'),
  '10/20/circle',
  'позиция и форма стола записаны'
);

SELECT is(
  (SELECT shape FROM tables WHERE id = 'a8200000-0000-4000-8000-000000000002'),
  'square',
  'не переданная форма не сбрасывается'
);

